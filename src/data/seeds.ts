export function getCityCoords(cityUrOrEn: string): { lat: number; lng: number } {
  const match = PAKISTANI_CITIES.find(
    (c) =>
      c.ur === cityUrOrEn ||
      c.en.toLowerCase() === cityUrOrEn.toLowerCase()
  );
  return match
    ? { lat: match.lat, lng: match.lng }
    : { lat: 30.1575, lng: 71.5249 };
}

export function getSeedMapUrl(seed: SeedItem): string {
  const cityCoords = getCityCoords(seed.cityEn || seed.cityUr);
  const coords =
    !seed.hideExactLocation && seed.lat !== undefined && seed.lng !== undefined
      ? { lat: seed.lat, lng: seed.lng }
      : cityCoords;
  return `https://www.google.com/maps/search/?api=1&query=${coords.lat},${coords.lng}`;
}

